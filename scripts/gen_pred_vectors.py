from fractions import Fraction
import random, math

random.seed(20261124)

def det(m):
    n = len(m)
    if n == 1:
        return m[0][0]
    total = Fraction(0)
    for j in range(n):
        minor = [[m[i][k] for k in range(n) if k != j] for i in range(1, n)]
        total += ((-1) ** j) * m[0][j] * det(minor)
    return total

def sign(v):
    return 1 if v > 0 else (-1 if v < 0 else 0)

o2, o3, ic, isph = [], [], [], []

# Large coordinates + tiny perturbations stress the floating-point filter.
for _ in range(120):
    b = random.randint(-10**8, 10**8)
    ax, ay = b, b + random.randint(-2, 2)
    bx, by = b + 1, b + 1 + random.choice([0, 1, -1, 2, -2])
    cx, cy = b + 2, b + 2 + random.choice([0, 1, -1, 2, -2])
    m = [[Fraction(ax),Fraction(ay),Fraction(1)],
         [Fraction(bx),Fraction(by),Fraction(1)],
         [Fraction(cx),Fraction(cy),Fraction(1)]]
    o2.append((ax,ay,bx,by,cx,cy,sign(det(m))))

for _ in range(120):
    a = tuple(random.randint(-10**6,10**6) for _ in range(3))
    b = (a[0]+random.randint(-2,2), a[1]+random.randint(-2,2), a[2]+random.randint(-2,2))
    c = (a[0]+random.randint(-2,2), a[1]+random.randint(-2,2), a[2]+random.randint(-2,2))
    d = (a[0]+random.randint(-2,2), a[1]+random.randint(-2,2), a[2]+random.randint(-2,2))
    m = [[Fraction(b[i]-a[i]) for i in range(3)],
         [Fraction(c[i]-a[i]) for i in range(3)],
         [Fraction(d[i]-a[i]) for i in range(3)]]
    o3.append((*a,*b,*c,*d,sign(det(m))))

for _ in range(120):
    r = random.randint(50,500)
    pts = []
    for k in range(3):
        ang = 2*math.pi*k/3
        pts.append((int(round(r*math.cos(ang))), int(round(r*math.sin(ang)))))
    q = (random.randint(-r,r), random.randint(-r,r))
    rows = pts + [q]
    m = [[Fraction(x),Fraction(y),Fraction(x)**2+Fraction(y)**2,Fraction(1)] for x,y in rows]
    ic.append((*(v for p in rows for v in p), sign(det(m))))

for _ in range(120):
    r = random.randint(20,100)
    pts = [tuple(random.randint(-r,r) for _ in range(3)) for _ in range(4)]
    q = tuple(random.randint(-r,r) for _ in range(3))
    rows = pts + [q]
    m = [[Fraction(x),Fraction(y),Fraction(z), Fraction(x)**2+Fraction(y)**2+Fraction(z)**2, Fraction(1)] for x,y,z in rows]
    s = sign(det(m))
    isph.append((*(v for p in rows for v in p), -s))  # negate: documented insphere convention

with open('/tmp/opencode/pred_vectors.h','w') as f:
    f.write('/* Generated by gen_pred_vectors.py; exact signs via Python Fraction. */\n')
    for name, rows in [('o2',o2),('o3',o3),('ic',ic),('is',isph)]:
        w = len(rows[0])-1
        f.write(f'static const double vec_{name}[][{w}] = {{\n')
        for r in rows:
            f.write('    { ' + ', '.join(str(float(v)) for v in r[:-1]) + ' },\n')
        f.write('};\n')
        f.write(f'static const int expect_{name}[] = {{ ' + ', '.join(str(r[-1]) for r in rows) + ' };\n')
        f.write(f'#define COUNT_{name} {len(rows)}\n\n')
print('wrote', len(o2), len(o3), len(ic), len(isph))
